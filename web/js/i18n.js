  // {n} - a value; {n|one|few|many} (ru) or {n|one|many} (en) - the word for that number
  function plural(n, forms) {
    const v = Math.abs(Number(String(n).replace(/[^0-9.-]/g, ''))) || 0;
    if (forms.length < 3) return v === 1 ? forms[0] : forms[1];
    const a = v % 10, b = v % 100;
    if (a === 1 && b !== 11) return forms[0];
    if (a >= 2 && a <= 4 && (b < 12 || b > 14)) return forms[1];
    return forms[2];
  }
  function fill(s, vars) {
    if (!vars) return s;
    return String(s)
      .replace(/\{(\w+)\|([^{}]+)\}/g, (m, k, f) => (k in vars ? plural(vars[k], f.split('|')) : m))
      .replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  }
